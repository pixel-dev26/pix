/**
 * The Video Studio reel — click a poster, that tile becomes a playing video.
 *
 * Six self-hosted files on one page is a lot to ask of a phone, so none of them is
 * fetched until someone asks for it. The <video> ships with no `src` anywhere: each
 * <source> carries `data-src`, which is inert, and this moves it to `src` and calls
 * load() on activation. Until then the tile costs one poster image.
 *
 * Only one plays at a time. Two soundtracks at once is the kind of thing that makes
 * people close the tab, and on mobile the browser will often stop the first one
 * anyway — better to do it deliberately and put the other tile back to its poster.
 *
 * The control is a real <button>, so Enter, Space and focus all work without help.
 * Unlike the site header there is no Webflow interaction to preserve here: this
 * markup is generated by scripts/build-site-seo.mjs and nothing else binds to it.
 */
(function () {
  'use strict';

  var cards = document.querySelectorAll('.psv-card[data-psv]');
  if (!cards.length) return;

  var playing = null;

  function stop(card) {
    if (!card) return;
    var video = card.querySelector('.psv-card__video');
    var button = card.querySelector('.psv-card__play');
    if (video) { try { video.pause(); } catch (_) {} video.hidden = true; }
    if (button) button.hidden = false;
    card.classList.remove('is-playing');
  }

  function activate(card) {
    var video = card.querySelector('.psv-card__video');
    var button = card.querySelector('.psv-card__play');
    if (!video || !button) return;

    if (playing && playing !== card) stop(playing);
    playing = card;

    // First click only: hand the real URLs over and load. After that the browser
    // has the file and re-clicks are just play().
    if (!card.dataset.psvLoaded) {
      var sources = video.querySelectorAll('source[data-src]');
      for (var i = 0; i < sources.length; i++) {
        sources[i].src = sources[i].getAttribute('data-src');
        sources[i].removeAttribute('data-src');
      }
      video.load();
      card.dataset.psvLoaded = '1';
    }

    button.hidden = true;
    video.hidden = false;
    card.classList.add('is-playing');

    // Focus follows the click, so the keyboard user lands on the controls of the
    // thing they just started rather than back at the top of the document.
    try { video.focus({ preventScroll: true }); } catch (_) {}

    var p = video.play();
    // Autoplay can be refused (low power mode, data saver). The controls are
    // already visible, so leave the video in place for the reader to press play
    // themselves rather than snapping the tile back to its poster underneath them.
    if (p && typeof p.catch === 'function') p.catch(function () {});
  }

  for (var i = 0; i < cards.length; i++) {
    (function (card) {
      var button = card.querySelector('.psv-card__play');
      if (button) button.addEventListener('click', function () { activate(card); });

      var video = card.querySelector('.psv-card__video');
      if (video) {
        // Back to the poster when it finishes, so the grid reads as a grid again
        // rather than a row of black rectangles on a last frame.
        video.addEventListener('ended', function () {
          stop(card);
          if (playing === card) playing = null;
        });
        video.addEventListener('play', function () {
          if (playing && playing !== card) stop(playing);
          playing = card;
        });
      }
    })(cards[i]);
  }

  // Escape stops whatever is running. Cheap, and the reflex everyone already has.
  document.addEventListener('keydown', function (e) {
    if ((e.key === 'Escape' || e.key === 'Esc') && playing) {
      var card = playing;
      stop(card);
      playing = null;
      var button = card.querySelector('.psv-card__play');
      if (button) try { button.focus({ preventScroll: true }); } catch (_) {}
    }
  });
})();
